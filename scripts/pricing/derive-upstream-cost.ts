/**
 * T-0583 (AUDIT-OPUS-1028 A3-03): record upstream_cost_usd = 0 for every tool of a provider that
 * genuinely costs nothing per call, derived from src/config/provider-limits.json, and say so in
 * tools.cost_source ('provider-limits:free') so a derived zero is distinguishable from a measured one.
 *
 * Law stays: a NULL cost never blocks a sale. This turns "unknown" into "known zero" only where
 * provider-limits.json shows a free plan with no paid tier. Everything else stays NULL and is listed
 * for the operator (--todo-md), the tools priced at $0.01 or more first.
 *
 * A provider is FREE iff its provider-limits.json entry
 *   - is not 'credits' / 'trial', and carries none of the paid-tier markers (PAID_KEYS: billing,
 *     paid_balance, balance_api, pricing_url, pricing_check, pricing_note). A provider with such a
 *     marker is the "PROVIDER_KEY_* with a paid plan" case: its key can be on a paid plan;
 *   - and is 'unlimited', or has a windowed free limit (hourly/daily/monthly/rate_limited) whose
 *     limit_proof says "free" and does not quote a per-call price (PER_CALL_PRICE: "$0.001/lookup above
 *     free tier", "PAYG", "per call"). Premise: no card is on file for a provider that is only windowed-free,
 *     so a soft or exceedable limit does not make calls cost money; a quoted per-call price means it could.
 *
 * Usage:
 *   npx tsx scripts/pricing/derive-upstream-cost.ts                    dry run against DATABASE_URL (read-only)
 *   npx tsx scripts/pricing/derive-upstream-cost.ts --from-tsv F       dry run from a tool_id<TAB>provider<TAB>price<TAB>cost dump
 *   npx tsx scripts/pricing/derive-upstream-cost.ts --apply            write via Prisma (cost IS NULL rows only)
 *   ... --todo-md PATH                                                 write the remaining-NULL owner list
 * DATABASE_URL in this repo's .env points at PROD: --apply is for the sandbox DB or the dispatcher.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

export const COST_SOURCE_FREE = 'provider-limits:free';
export const PAID_KEYS = [
  'billing',
  'paid_balance',
  'balance_api',
  'pricing_url',
  'pricing_check',
  'pricing_note',
] as const;
const PER_CALL_PRICE =
  /\$\d[\d.]*\s*\/\s*[a-z]|\bper[ -](call|lookup|request|credit)\b|\bpay-?as-?you-?go\b|\bpayg\b|above (the )?free/i;
const WINDOWED = new Set(['hourly', 'daily', 'monthly', 'rate_limited']);

export interface LimitEntry {
  limit_type?: unknown;
  limit_proof?: unknown;
  [k: string]: unknown;
}
export interface ToolRow {
  tool_id: string;
  provider: string;
  price_usd: number;
  cost: string | null;
}

export function isFreeProvider(entry: LimitEntry | undefined): boolean {
  if (!entry || typeof entry !== 'object') return false;
  if (PAID_KEYS.some((k) => k in entry)) return false;
  const type = entry.limit_type;
  if (type === 'unlimited') return true;
  const proof = entry.limit_proof;
  return (
    typeof type === 'string' &&
    WINDOWED.has(type) &&
    typeof proof === 'string' &&
    /\bfree\b/i.test(proof) &&
    !PER_CALL_PRICE.test(proof)
  );
}

export function planDerivation(rows: ToolRow[], limits: Record<string, LimitEntry>) {
  const derive: ToolRow[] = [];
  const remaining: ToolRow[] = [];
  for (const r of rows) {
    if (r.cost !== null) continue;
    (isFreeProvider(limits[r.provider]) ? derive : remaining).push(r);
  }
  return { derive, remaining };
}

export function tier(price: number): string {
  if (price >= 0.01) return '>= $0.01';
  if (price >= 0.001) return '$0.001 - $0.01';
  return '< $0.001';
}

export function todoMarkdown(
  remaining: ToolRow[],
  limits: Record<string, LimitEntry>,
  date: string,
): string {
  const paid = remaining.filter((r) => r.price_usd > 0);
  const byProvider = new Map<string, ToolRow[]>();
  for (const r of paid) byProvider.set(r.provider, [...(byProvider.get(r.provider) ?? []), r]);
  const maxPrice = (rs: ToolRow[]) => Math.max(...rs.map((r) => r.price_usd));
  const providers = [...byProvider.entries()].sort(
    (a, b) =>
      maxPrice(b[1]) - maxPrice(a[1]) || b[1].length - a[1].length || a[0].localeCompare(b[0]),
  );
  const high = paid
    .filter((r) => r.price_usd >= 0.01)
    .sort((a, b) => b.price_usd - a.price_usd || a.tool_id.localeCompare(b.tool_id));
  const out = [
    '# Paid tools with an unknown upstream cost',
    '',
    `Generated by \`scripts/pricing/derive-upstream-cost.ts --todo-md\` on ${date}.`,
    `${paid.length} paid tools across ${providers.length} providers have \`upstream_cost_usd\` NULL after the free-provider derivation (T-0583).`,
    'Owner: operator. Each provider needs one price-list read; record the result in `config/tool_provider_config.yaml` and re-seed. Nothing here is guessed.',
    '',
    `## Priced at $0.01 or more (${high.length} tools)`,
    '',
    '| tool_id | provider | price_usd |',
    '|---|---|---|',
    ...high.map((r) => `| \`${r.tool_id}\` | ${r.provider} | ${r.price_usd} |`),
    '',
    '## By provider',
    '',
    '| provider | tools | max price_usd | price tier | pricing marker in provider-limits.json |',
    '|---|---|---|---|---|',
    ...providers.map(([p, rs]) => {
      const marker =
        PAID_KEYS.filter((k) => limits[p] && k in limits[p]).join(', ') ||
        (limits[p] ? 'none (not free by rule)' : 'provider not in provider-limits.json');
      return `| ${p} | ${rs.length} | ${maxPrice(rs)} | ${tier(maxPrice(rs))} | ${marker} |`;
    }),
    '',
  ];
  return out.join('\n');
}

function parseTsv(path: string): ToolRow[] {
  return readFileSync(path, 'utf8')
    .split('\n')
    .filter((l) => l.trim() !== '')
    .map((l) => {
      const [tool_id, provider, price, cost] = l.split('\t');
      return {
        tool_id,
        provider,
        price_usd: Number(price),
        cost: cost === undefined || cost === '' ? null : cost,
      };
    });
}

async function main(): Promise<number> {
  const argv = process.argv.slice(2);
  const arg = (name: string) => {
    const i = argv.indexOf(name);
    return i >= 0 ? argv[i + 1] : undefined;
  };
  const apply = argv.includes('--apply');
  const tsv = arg('--from-tsv');
  const todoPath = arg('--todo-md');
  if (apply && tsv)
    throw new Error('--apply writes through Prisma; it cannot be combined with --from-tsv');

  const limits = JSON.parse(
    readFileSync(resolve(__dirname, '../../src/config/provider-limits.json'), 'utf8'),
  ) as Record<string, LimitEntry>;

  let rows: ToolRow[];
  let prisma: import('@prisma/client').PrismaClient | undefined;
  if (tsv) {
    rows = parseTsv(tsv);
  } else {
    const { PrismaClient } = await import('@prisma/client');
    prisma = new PrismaClient();
    const dbRows = await prisma.tool.findMany({
      select: { tool_id: true, provider: true, price_usd: true, upstream_cost_usd: true },
    });
    rows = dbRows.map((r) => ({
      tool_id: r.tool_id,
      provider: r.provider,
      price_usd: Number(r.price_usd),
      cost: r.upstream_cost_usd === null ? null : r.upstream_cost_usd.toString(),
    }));
  }

  const { derive, remaining } = planDerivation(rows, limits);
  const nullBefore = rows.filter((r) => r.cost === null).length;
  const paidBefore = rows.filter((r) => r.price_usd > 0);
  const known = (rs: ToolRow[]) => rs.filter((r) => r.cost !== null).length;
  const derivedPaid = derive.filter((r) => r.price_usd > 0).length;
  const paidKnownAfter = known(paidBefore) + derivedPaid;

  const byProvider = new Map<string, number>();
  for (const r of derive) byProvider.set(r.provider, (byProvider.get(r.provider) ?? 0) + 1);
  console.log('provider'.padEnd(34) + 'limit_type'.padEnd(14) + 'tools -> cost 0');
  for (const [p, n] of [...byProvider.entries()].sort(
    (a, b) => b[1] - a[1] || a[0].localeCompare(b[0]),
  )) {
    console.log(p.padEnd(34) + String(limits[p]?.limit_type).padEnd(14) + n);
  }
  console.log(
    `tools total ${rows.length}; cost NULL before ${nullBefore}; derived zero ${derive.length}; NULL after ${remaining.length}`,
  );
  console.log(
    `paid-tool coverage: ${known(paidBefore)}/${paidBefore.length} (${((100 * known(paidBefore)) / paidBefore.length).toFixed(1)}%) -> ` +
      `${paidKnownAfter}/${paidBefore.length} (${((100 * paidKnownAfter) / paidBefore.length).toFixed(1)}%)`,
  );
  const paidRemaining = remaining.filter((r) => r.price_usd > 0);
  const high = paidRemaining.filter((r) => r.price_usd >= 0.01);
  console.log(
    `remaining paid NULLs: ${paidRemaining.length} tools across ${new Set(paidRemaining.map((r) => r.provider)).size} providers; priced >= $0.01: ${high.length}`,
  );

  if (todoPath) {
    writeFileSync(todoPath, todoMarkdown(remaining, limits, new Date().toISOString().slice(0, 10)));
    console.log(`WROTE ${todoPath}`);
  }

  if (apply && prisma) {
    const res = await prisma.tool.updateMany({
      where: { tool_id: { in: derive.map((r) => r.tool_id) }, upstream_cost_usd: null },
      data: { upstream_cost_usd: '0', cost_source: COST_SOURCE_FREE },
    });
    console.log(
      `APPLIED: ${res.count} rows set to upstream_cost_usd 0, cost_source '${COST_SOURCE_FREE}'`,
    );
  } else {
    console.log('dry run -- pass --apply to write');
  }
  await prisma?.$disconnect();
  return 0;
}

if (require.main === module) {
  main().then(
    (c) => process.exit(c),
    (e) => {
      console.error(e);
      process.exit(1);
    },
  );
}
