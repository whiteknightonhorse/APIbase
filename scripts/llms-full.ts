/**
 * llms-full.ts (T-0591): static/llms-full.txt = static/llms.txt followed by the text of every
 * Markdown page that llms.txt links (https://apibase.pro/<path>.md -> static/<path>.md), in order of
 * first appearance. gen-discovery.ts writes it (and checks it byte for byte with --check);
 * `npx tsx scripts/llms-full.ts --check` runs the same comparison alone for sync-counts.sh (STALE_LLMS_FULL).
 */
import { existsSync, readFileSync } from 'fs';
import { resolve } from 'path';

const ROOT = resolve(__dirname, '..');
const SITE = 'https://apibase.pro/';

export function buildLlmsFull(root: string = ROOT): string {
  const llms = readFileSync(resolve(root, 'static/llms.txt'), 'utf8');
  const seen = new Set<string>();
  const parts: string[] = [
    '# APIbase: full text\n\nllms.txt followed by every Markdown page it links. Generated by scripts/llms-full.ts; do not edit.\n',
    `<!-- source: ${SITE}llms.txt -->\n\n${llms.trimEnd()}\n`,
  ];
  for (const m of llms.matchAll(/https:\/\/apibase\.pro\/([A-Za-z0-9._/-]+?\.md)\b/g)) {
    const rel = m[1];
    if (seen.has(rel)) continue;
    seen.add(rel);
    const file = resolve(root, 'static', rel);
    if (!file.startsWith(resolve(root, 'static') + '/') || !existsSync(file)) {
      throw new Error(`llms-full: llms.txt links ${SITE}${rel} but static/${rel} does not exist`);
    }
    parts.push(`<!-- source: ${SITE}${rel} -->\n\n${readFileSync(file, 'utf8').trimEnd()}\n`);
  }
  return parts.join('\n---\n\n');
}

if (require.main === module) {
  const target = resolve(ROOT, 'static/llms-full.txt');
  const want = buildLlmsFull();
  const have = existsSync(target) ? readFileSync(target, 'utf8') : null;
  if (process.argv.includes('--check')) {
    if (have !== want) {
      console.error(
        'STALE_LLMS_FULL static/llms-full.txt differs from scripts/llms-full.ts output; run npx tsx scripts/gen-discovery.ts',
      );
      process.exit(1);
    }
    console.log('llms-full --check: OK');
  } else {
    require('fs').writeFileSync(target, want);
    console.log(`llms-full: wrote ${target} (${want.length} bytes)`);
  }
}
