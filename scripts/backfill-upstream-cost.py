#!/usr/bin/env python3
"""backfill-upstream-cost.py -- T-0352: record upstream_cost_usd "0" explicitly for free providers.

A provider counts as FREE only on POSITIVE evidence of no-auth / free access:
  * connected.json says key_required false, OR provider-limits.json has limit_type "unlimited"
    with a limit_proof that states no API key / no auth / no registration is needed;
  * AND provider-limits.json carries no sign of money: no pricing_url / pricing_check / pricing_note /
    billing / paid_balance / balance_api block, and no credits / trial limit_type.
"status: connected" is NOT evidence of anything. Every other tool row that still has no
upstream_cost_usd is listed as UNKNOWN for the operator -- never guessed.

Only cost fields are touched; price_usd is never edited. Dry run by default.
Usage: python3 scripts/backfill-upstream-cost.py [--apply] [--write-unknown-md]
--write-unknown-md regenerates docs/margin/unknown-cost-providers.md (T-SITE-E): the list only shrinks.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
YAML_PATH = ROOT / "config" / "tool_provider_config.yaml"
UNKNOWN_MD_PATH = ROOT / "docs" / "margin" / "unknown-cost-providers.md"
LIMITS_PATH = ROOT / "src" / "config" / "provider-limits.json"
CONNECTED_PATH = ROOT / "scripts" / "night-orchestra" / "state" / "connected.json"
MONEY_KEYS = ("billing", "paid_balance", "balance_api", "pricing_check", "pricing_note", "pricing_url")
NO_AUTH_RE = re.compile(r"\bno\s+(api\s+)?(key|auth|authentication|registration|signup|sign-up)\b|without\s+(an\s+)?(api\s+)?key", re.I)

BLOCK_RE = re.compile(r"(?P<block>  - tool_id: [^\n]+\n(?:    [^\n]+\n)*)")


def free_providers(connected, limits):
    out = set()
    for name, lim in limits.items():
        if any(k in lim for k in MONEY_KEYS) or lim.get("limit_type") in ("credits", "trial"):
            continue
        no_auth_proof = lim.get("limit_type") == "unlimited" and NO_AUTH_RE.search(lim.get("limit_proof") or "")
        if no_auth_proof or connected.get(name, {}).get("key_required") is False:
            out.add(name)
    return out


def field(block, key):
    m = re.search(rf"^    {key}: \"?([^\"\n]*)\"?\s*$", block, re.M)
    return m.group(1).strip() if m else None


def plan(text, free):
    """Returns (new_text, zeroed_tool_ids, unknown {provider: [tool_id]})."""
    zeroed, unknown = [], {}

    def repl(m):
        block = m.group("block")
        if "    upstream_cost_usd:" in block:
            return block
        if "    upstream_cost_status: NOT_MEASURED\n" in block and "    upstream_cost_model: metered\n" in block:
            return block  # T-SITE-F0a: a metered block is a recorded cost model, not an unknown
        provider = field(block, "provider")
        tool_id = re.match(r"  - tool_id: (\S+)", block).group(1)
        try:
            paid = float(field(block, "price_usd") or 0) > 0
        except ValueError:
            paid = True
        if provider in free:
            zeroed.append(tool_id)
            return re.sub(r"(    price_usd: [^\n]+\n)", r'\1    upstream_cost_usd: "0"\n', block, count=1)
        if paid:
            unknown.setdefault(provider, []).append(tool_id)
        return block

    return BLOCK_RE.sub(repl, text), zeroed, unknown


def unknown_md(unknown):
    n = sum(len(v) for v in unknown.values())
    lines = [
        "# Paid tools without an upstream cost model",
        "",
        "Generated by `scripts/backfill-upstream-cost.py --write-unknown-md` (see docs/margin/COST-MODELS.md).",
        f"{n} paid tools across {len(unknown)} providers. The operator supplies a cost model (`upstream_cost_usd`) per provider; nothing here is guessed.",
        "A batch that gives a provider a cost model removes its section; a PR that ADDS a section is not done.",
        "",
    ]
    for p in sorted(unknown):
        lines += [f"## {p} ({len(unknown[p])})", ""] + [f"- `{t}`" for t in unknown[p]] + [""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--write-unknown-md", action="store_true")
    args = ap.parse_args()
    free = free_providers(json.loads(CONNECTED_PATH.read_text()), json.loads(LIMITS_PATH.read_text()))
    text = YAML_PATH.read_text()
    new_text, zeroed, unknown = plan(text, free)
    print(f"free providers (positive no-auth evidence, no pricing/billing marker): {len(free)}")
    print(f"tools that would get upstream_cost_usd 0: {len(zeroed)}")
    n_unknown = sum(len(v) for v in unknown.values())
    print(f"paid tools still without a cost model: {n_unknown} across {len(unknown)} provider(s)")
    for p in sorted(unknown):
        print(f"  UNKNOWN {p}: {len(unknown[p])} tool(s)")
    if args.write_unknown_md:
        UNKNOWN_MD_PATH.write_text(unknown_md(unknown))
        print(f"WROTE {UNKNOWN_MD_PATH}")
    if args.apply:
        YAML_PATH.write_text(new_text)
        print(f"APPLIED to {YAML_PATH}")
    else:
        print("dry run -- pass --apply to write")
    return 0


if __name__ == "__main__":
    sys.exit(main())
